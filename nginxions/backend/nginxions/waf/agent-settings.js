// WAF -> Agent: settings of the open-appsec agent and its advanced ML model.
// Settings are stored in nginxions_setting ("waf.agent") and written to nginxions-agent.env next to the
// policy (volume appsec-localconfig); the agent's entrypoint (deploy/openappsec/agent/nginxions-entry.sh)
// applies them at start and copies the file to nginxions-agent.applied. Saving restarts the agent.
// The advanced model is the .tgz the upstream entrypoint unpacks from /advanced-model at start.
// The model a manager uploaded goes to its nodes (step 15.5, docs/adr/0012-nodes.md 5e): its SHA-256 is in the signed
// package of each node, the node fetches the file, checks the hash and puts it in place; the model before an upload is
// kept, and going back to it (here, or on every node through the next package) is one button.
// The role of this server in the learning of several servers (step 15.4, docs/adr/0012-nodes.md 5c) goes in the same
// file: it is not a setting, it follows the nodes (applyLearningRole).
import { createWriteStream } from "node:fs";
import { link, mkdir, mkdtemp, readFile, rename, rm, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { pipeline } from "node:stream/promises";
import internalAuditLog from "../../internal/audit-log.js";
import errs from "../../lib/error.js";
import { debug, global as logger } from "../../logger.js";
import control from "../control/client.js";
import { learningRole } from "../nodes/role.js";
import { getSetting, setSetting } from "../settings.js";
import { fileInfo, MODEL_DIR, MODEL_FILE, PREVIOUS_FILE, sha256Of, validateModelArchive } from "./model-file.js";

const LOCALCONFIG_DIR = path.dirname(process.env.NGINXIONS_APPSEC_POLICY_FILE || "/ext/appsec/local_policy.yaml");
const ENV_FILE = path.join(LOCALCONFIG_DIR, "nginxions-agent.env");
const APPLIED_FILE = path.join(LOCALCONFIG_DIR, "nginxions-agent.applied");

const MODEL_MAX_BYTES = 1024 * 1024 * 1024;
// the agent runs in the openappsec container; its "restart" restarts the agent process (nginxions/control/server.js)
const AGENT_SERVICE = "openappsec";

// CrowdSec IP reputation of the agent stays off: for an IP that is not banned the agent drops the
// cached answer right after using it (layer_7_access_control.cc), so every request waits for a new
// lookup, about 1 s. The CrowdSec bouncer of NginxionS in nginx applies the same decisions without delay.
// The role: smartsync on (a manager: it has nodes) and the learning through the manager (a node); a server alone
// writes neither line, so its file stays as before.
const renderEnv = (s, role = {}) =>
	[
		"# Generated by NginxionS (WAF -> Agent), applied by the agent at start. Manual changes are overwritten.",
		"CROWDSEC_ENABLED=false",
		`NGINXIONS_FAIL_OPEN=${s.failOpen.enabled}`,
		`NGINXIONS_FAIL_OPEN_TIMEOUT_MS=${s.failOpen.timeoutMs}`,
		...(role.smartsync ? ["NGINXIONS_SMARTSYNC=true"] : []),
		...(role.viaManager ? ["NGINXIONS_LEARNING_VIA=manager"] : []),
		"",
	].join("\n");

const readText = async (file) => {
	try {
		return await readFile(file, "utf8");
	} catch {
		return null;
	}
};

const writeEnv = async (settings, role) => {
	await mkdir(LOCALCONFIG_DIR, { recursive: true });
	const tmp = `${ENV_FILE}.tmp`;
	await writeFile(tmp, renderEnv(settings, role ?? (await learningRole())));
	await rename(tmp, ENV_FILE);
};

/** the state of this node of a manager: its model is given by the manager (no upload here then) */
const managedByManager = async () => {
	const { readState } = await import("../nodes/member.js");
	const member = await readState();
	if (!member || member.disabled || !(member.model_sha256 || member.model_restart_pending)) return false;
	// a server that is a manager itself (its own node in a test) keeps its model in its hands
	return !(await learningRole()).smartsync;
};

const getModel = async () => ({
	...(await fileInfo(MODEL_FILE)),
	previous: await fileInfo(PREVIOUS_FILE),
	managed: await managedByManager().catch(() => false),
});

/** the current model goes to PREVIOUS_FILE (the one there before is dropped) */
const keepPrevious = async () => {
	try {
		await rename(MODEL_FILE, PREVIOUS_FILE);
	} catch (err) {
		if (err.code !== "ENOENT") throw err;
	}
};

let modelChanges = Promise.resolve();
const changeModel = (change) => {
	const result = modelChanges.then(change);
	modelChanges = result.catch(() => {});
	return result;
};

const replaceModel = async (incoming) => {
	// Keep the running model at its original path until the replacement is ready to rename over it.
	const backup = `${incoming}.previous`;
	try {
		await link(MODEL_FILE, backup);
		await rename(backup, PREVIOUS_FILE);
	} catch (err) {
		if (err.code !== "ENOENT") throw err;
	} finally {
		await rm(backup, { force: true });
	}
	await rename(incoming, MODEL_FILE);
};

// The agent loads its model at startup. A queued restart can also restart this backend, so check the agent's
// start time against the file's change time (updated by rename) even on a later heartbeat.
const restartForModel = async (changedAt) => {
	try {
		const agent = await control.getService(AGENT_SERVICE);
		if (agent.state === "running" && Date.parse(agent.startedAt) > changedAt) {
			if (agent.health === "starting") return { applied: false };
			if (!agent.health || agent.health === "healthy") return { applied: true };
		}
		const result = await control.restartService(AGENT_SERVICE, 1);
		return { applied: result.restarted === true };
	} catch (error) {
		return { applied: false, error };
	}
};

/**
 * On a node: verify and install the model named in the signed package, keeping the previous one.
 * @param {(file: string) => Promise<void>} fetchTo  writes the file of the manager
 * @param {string} sha256  the hash the package names
 * @returns {Promise<{applied: boolean, error?: Error}>} whether the agent has restarted with the model
 */
export const installManagerModel = (fetchTo, sha256) =>
	changeModel(async () => {
		if ((await fileInfo(MODEL_FILE)).sha256 !== sha256) {
			await mkdir(MODEL_DIR, { recursive: true });
			const tmp = `${MODEL_FILE}.manager`;
			try {
				await fetchTo(tmp);
				const got = await sha256Of(tmp);
				if (got !== sha256)
					throw new Error(`the model is not the one of the package (SHA-256 ${got.slice(0, 12)})`);
				await validateModelArchive(tmp);
				await replaceModel(tmp);
			} finally {
				await rm(tmp, { force: true });
			}
		}
		return restartForModel((await stat(MODEL_FILE)).ctimeMs);
	});

/** On a node: return to the model of the image, keeping the advanced model as the previous one. */
export const removeManagerModel = () =>
	changeModel(async () => {
		await keepPrevious();
		const previous = await stat(PREVIOUS_FILE).catch((err) => {
			if (err.code !== "ENOENT") throw err;
		});
		return previous ? restartForModel(previous.ctimeMs) : { applied: true };
	});

const state = async (settings) => {
	const applied = await readText(APPLIED_FILE);
	return {
		failOpen: settings.failOpen,
		// null: the agent has not started with NginxionS settings yet (older image or never restarted)
		restartRequired: applied === null ? null : applied !== renderEnv(settings, await learningRole()),
		model: await getModel(),
	};
};

/** at backend start: the agent reads the file at its next start */
const bootstrap = async () => {
	try {
		const settings = await getSetting("waf.agent");
		const role = await learningRole();
		if ((await readText(ENV_FILE)) !== renderEnv(settings, role)) {
			await writeEnv(settings, role);
		}
	} catch (err) {
		logger.error(`WAF agent settings: ${err.message}`);
		debug(logger, err);
	}
};

const restartAgent = (access) => control.restartService(AGENT_SERVICE, access.token.getUserId(1));

const ROLE_RESTART_DELAY_MS = 3000;
let roleRestart = null;

const hasLearningRole = (env, { smartsync, viaManager }) => {
	// The entrypoint defaults to standalone learning when there is no settings file.
	const lines = env?.split("\n") ?? [];
	return (
		lines.includes("NGINXIONS_SMARTSYNC=true") === smartsync &&
		lines.includes("NGINXIONS_LEARNING_VIA=manager") === viaManager
	);
};

/**
 * The role of this server changed (a node joined or left, the first node of a manager registered, the last one went):
 * the settings file of the agent gets it and the agent restarts to learn with it. Never throws: joining or disabling
 * a node does not fail on the agent; the error is logged and the restart is offered in WAF -> Agent.
 * @param {number} [userId]  who did it (audit of the restart); the system when a heartbeat found it
 * @returns {Promise<boolean>} the agent was asked to restart
 */
export const applyLearningRole = async (userId = 1) => {
	try {
		const settings = await getSetting("waf.agent");
		const role = await learningRole();
		const desired = renderEnv(settings, role);
		const [configured, applied] = await Promise.all([readText(ENV_FILE), readText(APPLIED_FILE)]);
		if (configured !== desired) await writeEnv(settings, role);
		// Reconcile the role even if a previous restart failed. Other agent settings have their own apply action.
		clearTimeout(roleRestart);
		roleRestart = null;
		if (hasLearningRole(applied, role)) return false;

		// One restart for changes that come together (a server joining itself: registered here, then joined).
		roleRestart = setTimeout(async () => {
			roleRestart = null;
			try {
				const [current, running] = await Promise.all([readText(ENV_FILE), readText(APPLIED_FILE)]);
				if (!hasLearningRole(current, role) || hasLearningRole(running, role)) return;
				logger.info(
					`Cluster: learning ${role.viaManager ? "through the manager" : "here"}, smartsync ${role.smartsync ? "on" : "off"}: the agent restarts`,
				);
				await control.restartService(AGENT_SERVICE, userId);
			} catch (err) {
				logger.warn(`Cluster: the agent did not restart for its learning role: ${err.message}`);
			}
		}, ROLE_RESTART_DELAY_MS);
		roleRestart.unref?.();
		return true;
	} catch (err) {
		logger.warn(`Cluster: the learning role of the agent: ${err.message}`);
		return false;
	}
};

const internalWafAgent = {
	/**
	 * @param {Access} access
	 */
	get: async (access) => {
		await access.can("waf_policy:view");
		return state(await getSetting("waf.agent"));
	},

	/**
	 * @param {Access}  access
	 * @param {{fail_open: {enabled, timeout_ms}}} data
	 * @param {boolean} [apply]  restart the agent now
	 */
	set: async (access, data, apply = true) => {
		await access.can("waf_policy:manage");
		const settings = await setSetting("waf.agent", {
			failOpen: { enabled: data.fail_open.enabled, timeoutMs: data.fail_open.timeout_ms },
		});
		await writeEnv(settings);
		await internalAuditLog.add(access, {
			action: "updated",
			object_type: "waf",
			meta: { name: "open-appsec agent", ...settings },
		});
		if (apply) {
			await restartAgent(access);
		}
		return { ...(await state(settings)), restarting: apply };
	},

	/**
	 * Streams the uploaded .tgz (request body) to the model volume; the agent unpacks it at start.
	 * @param {Access}          access
	 * @param {import("express").Request} req
	 * @param {boolean}         [apply]  restart the agent now
	 */
	uploadModel: async (access, req, apply = true) => {
		await access.can("waf_policy:manage");
		if (await managedByManager()) {
			throw new errs.ValidationError("The model of this node is given by its manager: upload it there");
		}
		const length = Number(req.headers["content-length"] || 0);
		if (length > MODEL_MAX_BYTES) {
			throw new errs.ValidationError("The model file is larger than 1 GB");
		}
		await mkdir(MODEL_DIR, { recursive: true });
		const staging = await mkdtemp(path.join(MODEL_DIR, ".upload-"));
		const tmp = path.join(staging, "model.tgz");
		let size = 0;
		req.on("data", (chunk) => {
			size += chunk.length;
			if (size > MODEL_MAX_BYTES) req.destroy(new Error("The model file is larger than 1 GB"));
		});
		try {
			await pipeline(req, createWriteStream(tmp, { mode: 0o644 }));
			await changeModel(async () => {
				await validateModelArchive(tmp);
				await replaceModel(tmp);
			});
		} catch (err) {
			throw err instanceof errs.ValidationError ? err : new errs.ValidationError(err.message);
		} finally {
			await rm(staging, { recursive: true, force: true });
		}
		await internalAuditLog.add(access, {
			action: "updated",
			object_type: "waf",
			meta: { name: "open-appsec advanced model", size },
		});
		if (apply) {
			await restartAgent(access);
		}
		return { ...(await getModel()), restarting: apply };
	},

	/**
	 * @param {Access}  access
	 * @param {boolean} [apply]  restart the agent now
	 */
	removeModel: async (access, apply = true) => {
		await access.can("waf_policy:manage");
		if (await managedByManager()) {
			throw new errs.ValidationError("The model of this node is given by its manager: change it there");
		}
		const had = await changeModel(async () => {
			const { present } = await fileInfo(MODEL_FILE);
			if (present) await keepPrevious();
			return present;
		});
		if (had) {
			await internalAuditLog.add(access, {
				action: "deleted",
				object_type: "waf",
				meta: { name: "open-appsec advanced model" },
			});
		}
		const restarting = apply && had;
		if (restarting) {
			await restartAgent(access);
		}
		return { ...(await getModel()), restarting };
	},
};

/**
 * Back to the model before (an upload or a removal is undone): the current one and the one before change places.
 * On a manager its nodes follow with their next package.
 * @param {Access}  access
 * @param {boolean} [apply]  restart the agent now
 */
internalWafAgent.previousModel = async (access, apply = true) => {
	await access.can("waf_policy:manage");
	if (await managedByManager()) {
		throw new errs.ValidationError("The model of this node is given by its manager: change it there");
	}
	await changeModel(async () => {
		if (!(await fileInfo(PREVIOUS_FILE)).present)
			throw new errs.ValidationError("There is no model before this one");
		await validateModelArchive(PREVIOUS_FILE);
		const swap = `${MODEL_FILE}.swap`;
		try {
			await link(MODEL_FILE, swap);
		} catch (err) {
			if (err.code !== "ENOENT") throw err;
		}
		try {
			await rename(PREVIOUS_FILE, MODEL_FILE);
			await rename(swap, PREVIOUS_FILE).catch((err) => {
				if (err.code !== "ENOENT") throw err;
			});
		} finally {
			await rm(swap, { force: true });
		}
	});
	await internalAuditLog.add(access, {
		action: "updated",
		object_type: "waf",
		meta: { name: "open-appsec advanced model", back: true },
	});
	if (apply) await restartAgent(access);
	return { ...(await getModel()), restarting: apply };
};

export { bootstrap, renderEnv };
export default internalWafAgent;
