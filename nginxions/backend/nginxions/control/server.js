#!/usr/bin/env node
import { timingSafeEqual } from "node:crypto";
import { takeCoverage } from "node:v8";
// NginxionS control plane (nginxions-control): the only way the NginxionS backend reaches the Docker API.
//
// Runs in a container of its own (service "control" of deploy/compose.yaml: the image of the agent with a command of
// its own), the only one with the Docker socket: neither nginxions nor the agent, which take the traffic of the
// internet, share its processes or files. It listens on the network "control", which only the openappsec container
// (and nginxions in its namespace) joins, and allows only a whitelist:
//   - only containers of this compose project labelled nginxions.managed=true;
//   - only these operations: list (state, health, version), restart, read logs, and a reload
//     (SIGHUP) of the services that reread their configuration on it (RELOADABLE).
// Every request needs the shared token generated by nginxions-init and is written to stdout as a JSON
// audit line (who, what, result). The backend also records user actions in the NginxionS audit log.
//
// No dependencies besides Node.js (the image copies this directory as is).
import { readFileSync } from "node:fs";
import http from "node:http";
import { hostname } from "node:os";
import {
	LearningError,
	listLearning,
	MAX_SNAPSHOT_BYTES,
	readLearning,
	snapshotLearning,
	stageRestore,
} from "./learning.js";
import { untarOne } from "./tar.js";
import { coordinateRestarts, repairNamespaces } from "./watchdog.js";

const PORT = Number.parseInt(process.env.NGINXIONS_CONTROL_PORT || "7080", 10);
// every address of this container: its only network is "control" (deploy/compose.yaml)
const LISTEN = process.env.NGINXIONS_CONTROL_LISTEN || "0.0.0.0";
const DOCKER_SOCKET = process.env.NGINXIONS_DOCKER_SOCKET || "/var/run/docker.sock";
// the service of the agent: its networks are those of nginx, its container holds the policy the agent applies
const AGENT_SERVICE = process.env.NGINXIONS_AGENT_SERVICE || "openappsec";
const TOKEN_FILE = process.env.NGINXIONS_CONTROL_TOKEN_FILE || "/run/secrets/control_token";
// the configuration the agent made of local_policy.yaml (local_policy_mgmt_gen.cc): what it applies; a file of the
// agent's container, read through the Docker API (archive)
const AGENT_POLICY_FILE = process.env.NGINXIONS_AGENT_POLICY_FILE || "/tmp/local_appsec.policy";
const AGENT_POLICY_MAX_BYTES = 32 * 1024 * 1024;
const DOCKER_TIMEOUT_MS = 15000;
// a restarted container is waited for until its healthcheck passes (the agent: its port 7777 answers)
const HEALTHY_TIMEOUT_MS = 180000;
const MAX_LOG_LINES = 5000;
// nginxions is restarted this long after nginxions-control has answered (see the restart route)
const RESTART_GRACE_MS = 2000;
const MANAGED_LABEL = "nginxions.managed";
const PROJECT_LABEL = "com.docker.compose.project";
const SERVICE_LABEL = "com.docker.compose.service";
// CrowdSec rereads acquisition, parsers, scenarios and profiles on SIGHUP: seconds instead of a restart
const RELOADABLE = ["crowdsec"];
const namespaceRestarts = coordinateRestarts();

const token = Buffer.from(readFileSync(TOKEN_FILE, "utf8").trim());
if (token.length < 32) {
	throw new Error(`${TOKEN_FILE}: token too short`);
}

const audit = (entry) => {
	process.stdout.write(`${JSON.stringify({ time: new Date().toISOString(), ...entry })}\n`);
};

class HttpError extends Error {
	constructor(status, message) {
		super(message);
		this.status = status;
	}
}

/**
 * The Docker API over its socket. Answers like fetch: {ok, status, json(), text(), arrayBuffer()}.
 * @param   {string} method
 * @param   {string} path    Docker API path with query
 */
const docker = (method, path) =>
	new Promise((resolve, reject) => {
		const req = http.request(
			{ socketPath: DOCKER_SOCKET, method, path, headers: { Host: "docker" }, timeout: DOCKER_TIMEOUT_MS },
			(res) => {
				const chunks = [];
				res.on("data", (c) => chunks.push(c));
				res.on("end", () => {
					const body = Buffer.concat(chunks);
					const status = res.statusCode ?? 0;
					const response = {
						ok: status >= 200 && status < 300,
						status,
						text: async () => body.toString("utf8"),
						json: async () => JSON.parse(body.toString("utf8") || "null"),
						arrayBuffer: async () => body,
						headers: res.headers,
					};
					if (!response.ok) {
						const err = new HttpError(
							502,
							`Docker API ${method} ${path.split("?")[0]}: ${status} ${body.toString("utf8").trim()}`,
						);
						err.dockerStatus = status;
						reject(err);
						return;
					}
					resolve(response);
				});
			},
		);
		req.on("timeout", () => req.destroy(new Error("timeout")));
		req.on("error", (err) => reject(new HttpError(502, `Docker API unreachable: ${err.code || err.message}`)));
		req.end();
	});

// The compose project is taken from this container's own labels, so several NginxionS stacks on one
// host never see each other's containers.
let project = null;
const getProject = async () => {
	if (!project) {
		const self = await (await docker("GET", `/containers/${encodeURIComponent(hostname())}/json`)).json();
		project = self.Config?.Labels?.[PROJECT_LABEL];
		if (!project) {
			throw new HttpError(500, "nginxions-control is not running as part of a compose project");
		}
	}
	return project;
};

const addressesOf = (c) =>
	Object.entries(c.NetworkSettings?.Networks ?? {})
		.filter(([, n]) => n.IPAddress)
		.map(([network, n]) => ({ network, ip: n.IPAddress }));

/** the ports a container listens on, once per port and protocol (published ones with the port of the host) */
const portsOf = (c) =>
	[
		...new Map(
			(c.Ports ?? []).map((p) => [
				`${p.PrivatePort}/${p.Type}`,
				{ port: p.PrivatePort, type: p.Type, published: p.PublicPort ?? null },
			]),
		).values(),
	].sort((x, y) => x.port - y.port || (x.type < y.type ? -1 : x.type > y.type ? 1 : 0));

const listManaged = async () => {
	const filters = JSON.stringify({ label: [`${PROJECT_LABEL}=${await getProject()}`, `${MANAGED_LABEL}=true`] });
	const containers = await (
		await docker("GET", `/containers/json?all=true&filters=${encodeURIComponent(filters)}`)
	).json();
	return containers.map((c) => ({
		id: c.Id,
		service: c.Labels[SERVICE_LABEL],
		name: (c.Names?.[0] || "").replace(/^\//, ""),
		image: c.Image,
		version: c.Labels["org.opencontainers.image.version"] || c.Image.split(":").pop() || null,
		state: c.State,
		status: c.Status,
		created: c.Created,
		restartable: true,
		networkMode: c.HostConfig?.NetworkMode || null,
		// addresses in its networks and the ports it listens on (published ones with the address of the host)
		addresses: addressesOf(c),
		ports: portsOf(c),
	}));
};

/**
 * The configuration the agent generated from local_policy.yaml, read only: NginxionS checks that the agent applies
 * what it wrote (WAF -> Policy). null before the agent applied a policy.
 */
const agentPolicy = async () => {
	const agent = await findService(AGENT_SERVICE);
	const path = `/containers/${agent.id}/archive?path=${encodeURIComponent(AGENT_POLICY_FILE)}`;
	let response;
	try {
		// the size first (a header of the answer to HEAD): a file too large is not read
		const head = await docker("HEAD", path);
		const stat = JSON.parse(
			Buffer.from(head.headers["x-docker-container-path-stat"] || "", "base64").toString() || "{}",
		);
		if (stat.size > AGENT_POLICY_MAX_BYTES) throw new HttpError(413, "the policy of the agent is too large");
		response = await docker("GET", path);
	} catch (err) {
		if (err.dockerStatus === 404) return { modifiedAt: null, policy: null };
		throw err;
	}
	let file;
	try {
		file = untarOne(Buffer.from(await response.arrayBuffer()));
	} catch (err) {
		throw new HttpError(502, `Docker API: ${err.message}`);
	}
	if (file.size > AGENT_POLICY_MAX_BYTES) throw new HttpError(413, "the policy of the agent is too large");
	return { modifiedAt: file.mtime.toISOString(), policy: JSON.parse(file.content.toString("utf8")) };
};

/**
 * Applications: running containers outside this stack in a network of nginxions, which nginx reaches by name. Read
 * only (name, image, addresses, ports): System -> Services offers to publish them as a proxy host.
 */
const listApps = async () => {
	const project = await getProject();
	const containers = await (await docker("GET", "/containers/json")).json();
	// nginx runs in the network namespace of openappsec: its networks are those of nginxions
	const own = containers.find(
		(c) => c.Labels?.[PROJECT_LABEL] === project && c.Labels?.[SERVICE_LABEL] === AGENT_SERVICE,
	);
	const networks = Object.keys(own?.NetworkSettings?.Networks ?? {});
	return containers
		.filter((c) => c.Labels?.[PROJECT_LABEL] !== project)
		.filter((c) => Object.keys(c.NetworkSettings?.Networks ?? {}).some((n) => networks.includes(n)))
		.map((c) => ({
			name: (c.Names?.[0] || "").replace(/^\//, ""),
			image: c.Image,
			status: c.Status,
			addresses: addressesOf(c).filter((a) => networks.includes(a.network)),
			ports: portsOf(c),
		}));
};

const findService = async (service) => {
	const container = (await listManaged()).find((c) => c.service === service);
	if (!container) {
		throw new HttpError(404, `Unknown service: ${service}`);
	}
	return container;
};

const inspect = async (service) => {
	const container = await findService(service);
	const details = await (await docker("GET", `/containers/${container.id}/json`)).json();
	return {
		...container,
		startedAt: details.State?.StartedAt || null,
		finishedAt: details.State?.FinishedAt || null,
		restartCount: details.RestartCount ?? 0,
		exitCode: details.State?.ExitCode ?? null,
		health: details.State?.Health?.Status || null,
		error: details.State?.Error || null,
	};
};

// Without a TTY the logs endpoint multiplexes stdout/stderr: 8-byte header (stream, 0,0,0, size BE32)
const demux = (buf) => {
	const lines = [];
	let offset = 0;
	while (offset + 8 <= buf.length) {
		const stream = buf[offset] === 2 ? "stderr" : "stdout";
		const size = buf.readUInt32BE(offset + 4);
		const chunk = buf.subarray(offset + 8, offset + 8 + size).toString("utf8");
		for (const line of chunk.split("\n")) {
			if (line !== "") {
				lines.push({ stream, line });
			}
		}
		offset += 8 + size;
	}
	return lines;
};

const logs = async (service, tail, since) => {
	const container = await findService(service);
	const params = new URLSearchParams({ stdout: "1", stderr: "1", timestamps: "1", tail: String(tail) });
	if (since) {
		params.set("since", String(since));
	}
	const response = await docker("GET", `/containers/${container.id}/logs?${params}`);
	return demux(Buffer.from(await response.arrayBuffer()));
};

/** a container restarted after `since` is healthy again (its healthcheck passed), or the time is up */
const healthyAgain = async (id, since, timeoutMs = HEALTHY_TIMEOUT_MS) => {
	const until = Date.now() + timeoutMs;
	while (Date.now() < until) {
		await new Promise((resolve) => setTimeout(resolve, 2000));
		const state = (await (await docker("GET", `/containers/${id}/json`)).json()).State ?? {};
		if (!(Date.parse(state.StartedAt || "") >= since)) continue;
		if (!state.Health || state.Health.Status === "healthy") return true;
	}
	return false;
};

/**
 * A container, then the containers in its namespaces (nginxions in openappsec's): they keep the old namespace after a
 * restart and lose the network. The restarted one is first waited for until healthy, so that the nginx attachment
 * attaches to the new agent.
 */
const restartWithDependents = async (container, entry) => {
	const since = Date.now() - 1000;
	await docker("POST", `/containers/${container.id}/restart?t=10`);
	const dependents = (await listManaged()).filter((c) => c.networkMode === `container:${container.id}`);
	if (dependents.length && !(await healthyAgain(container.id, since))) {
		audit({ ...entry, result: "slow to become healthy", service: container.service });
	}
	for (const dependent of dependents) {
		await docker("POST", `/containers/${dependent.id}/restart?t=10`);
		audit({ ...entry, result: "restarted dependent", dependent: dependent.service });
	}
};

const authorized = (req) => {
	const header = req.headers.authorization || "";
	const given = Buffer.from(header.startsWith("Bearer ") ? header.slice(7) : "");
	return given.length === token.length && timingSafeEqual(given, token);
};

const send = (res, status, body) => {
	res.writeHead(status, { "Content-Type": "application/json" });
	res.end(JSON.stringify(body));
};

/** a JSON request body of at most `limit` bytes */
const readJson = (req, limit) =>
	new Promise((resolve, reject) => {
		const chunks = [];
		let size = 0;
		req.on("data", (chunk) => {
			size += chunk.length;
			if (size > limit) {
				reject(new HttpError(413, "Request body too large"));
				req.destroy();
				return;
			}
			chunks.push(chunk);
		});
		req.on("end", () => {
			try {
				resolve(JSON.parse(Buffer.concat(chunks).toString("utf8")));
			} catch {
				reject(new HttpError(400, "Invalid JSON"));
			}
		});
		req.on("error", reject);
	});

const intParam = (value, fallback, max) => {
	const n = Number.parseInt(value ?? "", 10);
	return Number.isFinite(n) && n > 0 ? Math.min(n, max) : fallback;
};

const server = http.createServer(async (req, res) => {
	const url = new URL(req.url, "http://nginxions-control");
	const actor = `${req.headers["x-nginxions-actor"] || ""}`.slice(0, 200) || null;
	const entry = { actor, method: req.method, path: url.pathname };

	if (url.pathname === "/healthz") {
		return send(res, 200, { status: "OK" });
	}
	if (!authorized(req)) {
		audit({ ...entry, result: "denied" });
		return send(res, 401, { error: "Unauthorized" });
	}

	try {
		const parts = url.pathname.split("/").filter(Boolean);
		let result;
		let after = null;

		if (req.method === "GET" && url.pathname === "/v1/services") {
			result = await listManaged();
		} else if (req.method === "GET" && url.pathname === "/v1/apps") {
			result = await listApps();
		} else if (req.method === "GET" && url.pathname === "/v1/agent/policy") {
			result = await agentPolicy();
		} else if (req.method === "GET" && url.pathname === "/v1/agent/learning") {
			// what the agent learned, read only (learning.js)
			result = await listLearning();
		} else if (req.method === "GET" && url.pathname === "/v1/agent/learning/file") {
			result = await readLearning(url.searchParams.get("asset") || "", url.searchParams.get("name") || "");
		} else if (req.method === "GET" && url.pathname === "/v1/agent/learning/snapshot") {
			// every learned file as it is, for a snapshot of NginxionS (learning/snapshots.js)
			result = await snapshotLearning();
		} else if (req.method === "POST" && url.pathname === "/v1/agent/learning/restore") {
			// a snapshot back in place: staged, then put in place by the next start of the agent (nginxions-entry.sh);
			// the agent and nginxions are restarted as by a restart of this service (base64: a third more than the files)
			const files = await stageRestore(await readJson(req, Math.ceil(MAX_SNAPSHOT_BYTES * 1.4) + 65536));
			const container = await findService(AGENT_SERVICE);
			after = () => namespaceRestarts.restart(() => restartWithDependents(container, entry));
			result = { restored: files, restarting: true };
		} else if (parts[0] === "v1" && parts[1] === "services" && parts.length >= 3) {
			const service = decodeURIComponent(parts[2]);
			const action = parts[3];
			if (req.method === "GET" && !action) {
				result = await inspect(service);
			} else if (req.method === "GET" && action === "logs") {
				const since = intParam(url.searchParams.get("since"), 0, Number.MAX_SAFE_INTEGER);
				result = await logs(service, intParam(url.searchParams.get("tail"), 200, MAX_LOG_LINES), since);
			} else if (req.method === "POST" && action === "reload") {
				const container = await findService(service);
				if (!RELOADABLE.includes(container.service)) {
					throw new HttpError(400, `${service} cannot be reloaded`);
				}
				await docker("POST", `/containers/${container.id}/kill?signal=SIGHUP`);
				result = { service, reloaded: true };
			} else if (req.method === "POST" && action === "restart") {
				const container = await findService(service);
				const doRestart = () => restartWithDependents(container, entry);
				// answer first when the restart reaches nginxions (itself, or openappsec whose namespace it is in): it
				// cuts the backend's own request
				const reachesBackend =
					container.service === "nginxions" ||
					(await listManaged()).some((c) => c.networkMode === `container:${container.id}`);
				if (reachesBackend) {
					after = () => namespaceRestarts.restart(doRestart);
					result = { service, restarted: false, restarting: true };
				} else {
					await doRestart();
					result = { service, restarted: true };
				}
			}
		}

		if (result === undefined) {
			throw new HttpError(404, "Unknown operation");
		}
		// reads are frequent (status page polling); only changes go to the audit log
		if (req.method !== "GET") {
			audit({ ...entry, result: "ok" });
		}
		send(res, req.method === "POST" ? 202 : 200, result);
		if (after) {
			// the backend still has to pass this answer on to its own client through nginx: a restart right
			// away can cut that answer (curl: unexpected eof), so give it a moment
			await new Promise((resolve) => setTimeout(resolve, RESTART_GRACE_MS));
			after().then(
				() => audit({ ...entry, result: "restarted" }),
				(err) => audit({ ...entry, result: "failed", error: err.message }),
			);
		}
	} catch (err) {
		const status = err instanceof HttpError || err instanceof LearningError ? err.status : 500;
		audit({ ...entry, result: "error", status, error: err.message });
		send(res, status, { error: err.message });
	}
});

server.listen(PORT, LISTEN, () => {
	audit({ event: "listening", address: `${LISTEN}:${PORT}`, docker: DOCKER_SOCKET });
});

const inspectContainer = async (id) => (await docker("GET", `/containers/${id}/json`)).json();
const restartContainer = (id) => docker("POST", `/containers/${id}/restart?t=10`);

const WATCHDOG_MS = 30 * 1000;
const repairAll = () => repairNamespaces(listManaged, inspectContainer, restartContainer);
if (process.env.NGINXIONS_CONTROL_WATCHDOG !== "false") {
	const tick = () =>
		namespaceRestarts.repair(repairAll).then(
			(repaired) => {
				for (const service of repaired)
					audit({ actor: "watchdog", result: "restarted", service, reason: "network namespace" });
			},
			// the Docker API may not answer yet at boot: the next tick tries again
			() => undefined,
		);
	setTimeout(tick, 5000).unref();
	setInterval(tick, WATCHDOG_MS).unref();
}

for (const signal of ["SIGINT", "SIGTERM"]) {
	process.on(signal, () => server.close(() => process.exit(0)));
}
// the coverage of the tests of the stack: with NODE_V8_COVERAGE (only in deploy/test/compose.airgap.yaml) SIGUSR2
// writes what nginxions-control ran so far (scripts/test-airgap.sh collects it)
if (process.env.NODE_V8_COVERAGE) process.on("SIGUSR2", () => takeCoverage());
